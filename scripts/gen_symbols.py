    ("Search", "search", False), ("Add", "add", False), ("Send", "send", False),
    ("Settings", "settings", False), ("Check", "check", False), ("Close", "close", False),
    ("Refresh", "refresh", False), ("Back", "arrow_back", False),
    ("Home", "home", False), ("HomeFill", "home", True),
    ("Devices", "devices", False), ("DevicesFill", "devices", True),
    ("Explore", "explore", False), ("ExploreFill", "explore", True),
    ("Person", "person", False), ("PersonFill", "person", True),
    ("Tag", "tag", False),
    ("Favorite", "favorite", True), ("FavoriteOutline", "favorite", False),
    ("Bookmark", "bookmark", True), ("BookmarkOutline", "bookmark", False),
    ("Folder", "folder", False), ("Comment", "chat_bubble", False),
    ("Forward", "forward", False), ("Share", "share", False),
    ("History", "history", False), ("Mail", "mail", False), ("Logout", "logout", False),
    ("OpenInNew", "open_in_new", False), ("ChevronLeft", "chevron_left", False),
    ("ChevronRight", "chevron_right", False), ("Verified", "verified", True),
    ("More", "more_vert", False), ("Delete", "delete", False), ("PlayArrow", "play_arrow", True), ("Download", "download", False),
    ("Article", "article", False), ("Copy", "content_copy", False), ("Flag", "flag", False), ("Block", "block", False), ("Footprint", "footprint", False),
