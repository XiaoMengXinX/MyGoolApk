#!/usr/bin/env python3
"""Generates internal/app/symbols_gen.go from Material Symbols Rounded (weight 400, opsz 24).

Run from app-nsgo/: python3 scripts/gen_symbols.py
"""
import re
import urllib.request

BASE = "https://raw.githubusercontent.com/google/material-design-icons/master/symbols/web"

# (Go field, Material Symbols name, filled)
ICONS = [
    ("Search", "search", False), ("Add", "add", False), ("Send", "send", False),
    ("Settings", "settings", False), ("Check", "check", False), ("Close", "close", False),
    ("Refresh", "refresh", False), ("Back", "arrow_back", False),
    ("Home", "home", False), ("HomeFill", "home", True),
    ("Devices", "devices", False), ("DevicesFill", "devices", True),
    ("Explore", "explore", False), ("ExploreFill", "explore", True),
    ("Person", "person", False), ("PersonFill", "person", True),
    ("Tag", "tag", False),
    ("Favorite", "favorite", True), ("FavoriteOutline", "favorite", False),
    ("Bookmark", "bookmark", True), ("BookmarkOutline", "bookmark", False),
    ("Folder", "folder", False), ("Comment", "chat_bubble", False),
    ("Forward", "forward", False), ("Share", "share", False),
    ("History", "history", False), ("Mail", "mail", False), ("Logout", "logout", False),
    ("OpenInNew", "open_in_new", False), ("ChevronLeft", "chevron_left", False),
    ("ChevronRight", "chevron_right", False), ("Verified", "verified", True),
    ("More", "more_vert", False), ("Delete", "delete", False), ("PlayArrow", "play_arrow", True), ("Download", "download", False),
    ("Article", "article", False), ("Copy", "content_copy", False), ("Flag", "flag", False), ("Block", "block", False), ("Footprint", "footprint", False),
    ("ThumbUp", "thumb_up", True), ("Campaign", "campaign", True), ("MailFill", "mail", True), ("Link", "link", False), ("Star", "star", True),
]


def path(name, filled):
    suffix = "_fill1" if filled else ""
    url = f"{BASE}/{name}/materialsymbolsrounded/{name}{suffix}_24px.svg"
    for attempt in range(4):
        try:
            svg = urllib.request.urlopen(url, timeout=30).read().decode()
            break
        except OSError:
            if attempt == 3:
                raise
    paths = re.findall(r'<path d="([^"]+)"', svg)
    assert len(paths) == 1, (name, len(paths))
    return paths[0]


lines = ["// Code generated by scripts/gen_symbols.py; DO NOT EDIT.", "", "package app", "",
                  "// symbols holds Material Symbols Rounded (weight 400, 24px), each parsed on first use.",
         "var symbols = struct {"]
for field, _, _ in ICONS:
    lines.append(f"\t{field} symbol")
lines += ["}{"]
for field, name, filled in ICONS:
    lines.append(f'\t{field}: symbol{{path: "{path(name, filled)}"}},')
lines += ["}", ""]
open("internal/app/symbols_gen.go", "w").write("\n".join(lines))

import subprocess
subprocess.run(["gofmt", "-w", "internal/app/symbols_gen.go"], check=True)
